        private static readonly Regex VoiceName = new Regex(
            @"^(?<sec>[a-z]\d\d)_(?<ch>[a-z]+)_(?<n1>\d\d)(?:_(?<n2>\d\d))?(?:_p(?<part>\d+))?_(?<take>[a-z])$");
        private static readonly Regex SoundName = new Regex(@"^(?<id>[a-z]\d\d_sfx_\d\d)(?:_(?<variant>[a-z0-9]+))?$");

        private List<StoryItem> m_Items = new List<StoryItem>();
        private Dictionary<string, StagingEntry> m_Staging = new Dictionary<string, StagingEntry>();
        // voice id -> take -> parts (part number -> clip)
        private readonly Dictionary<string, Dictionary<string, SortedDictionary<int, AudioClip>>> m_Voices =
            new Dictionary<string, Dictionary<string, SortedDictionary<int, AudioClip>>>();
        // voice ids whose audio is inside another line's recording (e.g. p00_narr_02_03_a covers p00_narr_03)
        private readonly HashSet<string> m_CoveredByPrevious = new HashSet<string>();
        private readonly Dictionary<string, AudioClip> m_Sounds = new Dictionary<string, AudioClip>();
        // Sound id -> variant suffix -> clip (s02_sfx_14_grave.wav: "grave"); picked by the register.
        private readonly Dictionary<string, Dictionary<string, AudioClip>> m_SoundVariants =
            new Dictionary<string, Dictionary<string, AudioClip>>();
        // Every clip by its file name, for extra beds named in the staging (e.g. x_vento_alberi).
        private readonly Dictionary<string, AudioClip> m_ClipsByName = new Dictionary<string, AudioClip>();
        private readonly List<SpatialSource> m_Foreground = new List<SpatialSource>();
        // Looping background sounds, with the id of the item that ends them.
        private readonly List<(SpatialSource source, string until)> m_Beds = new List<(SpatialSource, string)>();
        // Sounds that keep playing under the next item (staging "attesa" shorter than the clip).
        private readonly List<SpatialSource> m_Tails = new List<SpatialSource>();

        private Coroutine m_Run;
        private bool m_Skip, m_Repeat;
        private int m_Choice = -1;

        private void Awake()
        {
            InputSystem.settings.backgroundBehavior = InputSettings.BackgroundBehavior.IgnoreFocus;
            if (sequence != null) m_Items = StoryData.ParseSequence(sequence.text);
            if (staging != null) m_Staging = StoryData.ParseStaging(staging.text);
            IndexClips();
        }

        private IEnumerator Start()
        {
            // "C2_03_Scena3" -> "C2": this chapter counts as played (until the game saves progress).
            string scene = UnityEngine.SceneManagement.SceneManager.GetActiveScene().name;
            if (scene.IndexOf('_') > 0) PlayedChapters.Add(scene.Substring(0, scene.IndexOf('_')));
            Status = autoStart ? "Sto per cominciare..." : "Premi Spazio per cominciare";
            if (autoStart) yield return new WaitForSeconds(startDelay);
            else
            {
                Paused = true;
                while (Paused) yield return null;
            }
            // A jump from the overlay may have started playback already.
            if (m_Run == null) Restart();
        }


        private void IndexClips()
        {
            foreach (var clip in clips)
            {
                if (clip == null) continue;
                m_ClipsByName[clip.name] = clip;
                var v = VoiceName.Match(clip.name);
                if (v.Success && v.Groups["ch"].Value != "sfx")
                {
                    int first = int.Parse(v.Groups["n1"].Value);
                    int last = v.Groups["n2"].Success ? int.Parse(v.Groups["n2"].Value) : first;
                    int part = v.Groups["part"].Success ? int.Parse(v.Groups["part"].Value) : 1;
                    string prefix = v.Groups["sec"].Value + "_" + v.Groups["ch"].Value + "_";
                    string id = prefix + first.ToString("00");
                    if (!m_Voices.TryGetValue(id, out var takes)) m_Voices[id] = takes = new Dictionary<string, SortedDictionary<int, AudioClip>>();
                    if (!takes.TryGetValue(v.Groups["take"].Value, out var parts)) takes[v.Groups["take"].Value] = parts = new SortedDictionary<int, AudioClip>();
                    parts[part] = clip;
                    for (int n = first + 1; n <= last; n++) m_CoveredByPrevious.Add(prefix + n.ToString("00"));
                    continue;
                }
                var s = SoundName.Match(clip.name);
                if (!s.Success) continue;
                string soundId = s.Groups["id"].Value;
                if (!m_Sounds.ContainsKey(soundId) || !s.Groups["variant"].Success) m_Sounds[soundId] = clip;
                if (s.Groups["variant"].Success)
                {
                    if (!m_SoundVariants.TryGetValue(soundId, out var variants))
                        m_SoundVariants[soundId] = variants = new Dictionary<string, AudioClip>();
                    variants[s.Groups["variant"].Value] = clip;
                }
            }
        }

        /// <summary>The clip of a sound, in the chosen register when the sound has register variants.</summary>
        private bool SoundClip(string id, out AudioClip clip)
        {
            if (m_SoundVariants.TryGetValue(id, out var variants) && variants.TryGetValue(Register, out clip)) return true;
            return m_Sounds.TryGetValue(id, out clip);
        }

        private List<AudioClip> VoiceParts(string id, out string usedTake)
        {
            usedTake = "";
            if (!m_Voices.TryGetValue(id, out var takes) || takes.Count == 0) return null;
            if (!takes.TryGetValue(take, out var parts))
            {
                var keys = new List<string>(takes.Keys);
                keys.Sort();
                usedTake = keys[0];
                parts = takes[usedTake];
            }
            else usedTake = take;
            return new List<AudioClip>(parts.Values);
        }

        public StagingEntry StagingFor(StoryItem item)
        {
            if (m_Staging.TryGetValue(item.Id, out var e)) return e;
            if (m_Staging.TryGetValue(item.Code, out e)) return e;
            if (item.Kind == StoryItemKind.Sound && m_Staging.TryGetValue("sfx", out e)) return e;
            return StagingEntry.Default;
        }

        private Material MarkerFor(StoryItem item) => item.Code switch
        {
            "sfx" => soundMarker,
            "vent" => windMarker,
            "lont" => distantMarker,
            _ => characterMarker,
        };


        public void Restart() => Begin(null, "A");

        private void Begin(string fromId, string branch)
        {
            m_StartOverride = fromId;
            if (m_Run != null) StopCoroutine(m_Run);
            EndInteractionCapture();
            m_EncouragementIndex = 0;
            StopBattle();
            foreach (var s in Active.ToArray()) s.Stop();
            m_Foreground.Clear();
            m_Beds.Clear();
            m_Tails.Clear();
            Paused = false;
            AudioListener.pause = false;
            m_Skip = m_Repeat = false;
            BranchChoice = branch;
            m_Run = StartCoroutine(RunSection());
        }

        public void TogglePause()
        {
            Paused = !Paused;
            AudioListener.pause = Paused;
            RebaseInteractionClock();
        }

        public void Skip() => m_Skip = true;
        public void Repeat() => m_Repeat = true;

        private void Update()
        {
            var kb = Keyboard.current;
            if (kb != null)
            {
                if (kb.spaceKey.wasPressedThisFrame)
                {
                    if (WaitingChoice) m_Choice = 0;
                    else TogglePause();
                }
                if (kb.rKey.wasPressedThisFrame) Repeat();
                if (kb.nKey.wasPressedThisFrame && Current?.Kind != StoryItemKind.Interaction) Skip();
                if (kb.backspaceKey.wasPressedThisFrame) Restart();
                if (kb.digit1Key.wasPressedThisFrame) m_Choice = 0;
                if (kb.digit2Key.wasPressedThisFrame) m_Choice = 1;
                if (kb.digit3Key.wasPressedThisFrame) m_Choice = 2;
                if (kb.digit4Key.wasPressedThisFrame) m_Choice = 3;

                if (listener != null)
                {
                    float turn = (kb.rightArrowKey.isPressed ? 1f : 0f) - (kb.leftArrowKey.isPressed ? 1f : 0f);
                    listener.Rotate(0f, turn * headTurnDegreesPerSecond * Time.unscaledDeltaTime, 0f);
                    if (kb.homeKey.wasPressedThisFrame) listener.rotation = Quaternion.identity;
                }
            }

            // Ducking: background beds get quieter while a voice is playing.
            bool voicePlaying = false;
            if (ducking)
                foreach (var s in Active)
                    if (s != null && s.IsVoice && s.Source.isPlaying) { voicePlaying = true; break; }
            foreach (var (bed, _) in m_Beds)
                if (bed != null) bed.TargetGain = voicePlaying ? duckGain : 1f;
            m_Tails.RemoveAll(t => t == null);
            foreach (var tail in m_Tails) tail.TargetGain = voicePlaying ? soundDuckGain : 1f;
            UpdateBattleLayers(voicePlaying);

            var pad = EchoQuestController.current;
            if (pad != null)
            {
                for (int b = 0; b < 4; b++)
                {
                    var button = pad.TryGetChildControl<ButtonControl>("button" + (b + 1));
                    if (button != null && button.wasPressedThisFrame) m_Choice = b;
                }
                if (headFollowsController && listener != null)
                    listener.rotation = Quaternion.Euler(0f, pad.yawDegrees - headYawOffset, 0f);
            }
        }


        private IEnumerator RunSection()
        {
            var list = m_Items.FindAll(i => i.Section == section);
            ItemCount = list.Count;
            int index = 0;
            string from = m_StartOverride ?? startFrom;
            if (!string.IsNullOrEmpty(from))
                index = Mathf.Max(0, list.FindIndex(i => i.Id == from));

            StoryItem previous = null;
            float pendingPause = 0f;
            while (true)
            {
                if (index >= list.Count)
                {
                    // The chapter goes on in the same scene: the next section starts after a normal
                    // pause, while the last sound of this one may still be ringing.
                    string next = continueToNextSection ? NextSection(section) : null;
                    if (next == null) break;
                    section = next;
                    BranchChoice = "A";
                    LogEvent("section " + next);
                    list = m_Items.FindAll(i => i.Section == section);
                    ItemCount = list.Count;
                    index = 0;
                    pendingPause += pauseBetweenSections;
                    continue;
                }
                var item = list[index];
                ItemIndex = index;
                bool playedInsideVoice = item.Kind == StoryItemKind.Sound && !string.IsNullOrEmpty(item.Inside);
                bool otherBranch = !string.IsNullOrEmpty(item.Branch) && item.Branch != BranchChoice;
                if (playedInsideVoice || otherBranch || m_CoveredByPrevious.Contains(item.Id)) { index++; continue; }

                // Breathing room between lines: longer when someone else starts speaking.
                float pause = pendingPause;
                if (item.Kind == StoryItemKind.Voice && previous != null && previous.Kind == StoryItemKind.Voice &&
                    previous.Character != item.Character && !StagingFor(previous).PauseAfter.HasValue)
                    pause = Mathf.Max(pause, pauseOnSpeakerChange);
                if (pause > 0f && !m_Repeat)
                {
                    Status = "Pausa";
                    yield return Wait(pause);
                }

                m_Skip = m_Repeat = false;
                Current = item;
                LogEvent(item.Id + (string.IsNullOrEmpty(item.Branch) ? "" : " [" + item.Branch + "]"));
                EndBedsUntil(item.Id);
                double? onTheBeat = EndBattleAt(item);
                switch (item.Kind)
                {
                    case StoryItemKind.Voice:
                        yield return PlayVoice(item, list.FindAll(i => i.Inside == item.Id));
                        break;
                    case StoryItemKind.Sound:
                        yield return PlaySound(item, onTheBeat);
                        break;
                    case StoryItemKind.Interaction:
                        if (StagingFor(item).Interaction is { } interaction)
                            yield return PlayInteraction(item, interaction);
                        else
                            yield return WaitForChoice(item, list, index);
                        break;
                }

                bool repeat = m_Repeat;
                StopForeground();
                if (repeat) { pendingPause = 0f; continue; }

                var itemStaging = StagingFor(item);
                if (itemStaging.PauseAfter.HasValue) pendingPause = Mathf.Max(0f, itemStaging.PauseAfter.Value);
                else if (item.Kind == StoryItemKind.Voice)
                    pendingPause = EndsWithQuestion(item.Text) ? pauseAfterQuestion : pauseAfterLine;
                else if (item.Kind == StoryItemKind.Sound)
                    pendingPause = itemStaging.Loop || itemStaging.Wait.HasValue ? 0f : pauseAfterSound;
                else pendingPause = 0f;
                previous = item;
                index++;
            }
            EndBedsUntil(null);
            StopBattle();
            Current = null;
            CurrentClip = "";
            Status = continueToNextSection ? "Fine del capitolo. Backspace per ricominciare."
                                           : "Fine della scena. Backspace per ricominciare.";
            // The chapter the child chose goes on straight away (until the menu exists).
            if (continueToNextSection && NextChapterFrom == ChapterName && !string.IsNullOrEmpty(NextChapterScene))
            {
                string scene = NextChapterScene;
                NextChapterScene = NextChapterFrom = "";
                LogEvent("next chapter: " + scene);
                Status = "Si continua con il capitolo scelto...";
                yield return Wait(pauseBetweenSections + pauseAfterLine);
                UnityEngine.SceneManagement.SceneManager.LoadScene(scene);
            }
        }

        /// <summary>The scene to open when this chapter ends, chosen in it (chapter 1, Scene 5), and the
        /// chapter that chose it. Static, so it survives the load of the next scene.</summary>
        public static string NextChapterScene = "", NextChapterFrom = "";
        /// <summary>The chapters opened in this session ("C1", "C2"...). An epilogue's "go on to the next
        /// instrument" skips a chapter already played (docs/capitoli-2-3.md: "il capitolo successivo non
        /// ancora giocato"); with none left the chapter ends, until the menu exists.</summary>
        public static readonly HashSet<string> PlayedChapters = new HashSet<string>();
        private string ChapterName => sequence != null ? sequence.name : "";

        private void RememberNextChapter(StoryItem item, string branch)
        {
            var map = StagingFor(item).NextChapter;
            if (map.Count == 0) return;
            NextChapterScene = map.TryGetValue(branch, out var scene) ? scene : "";
            NextChapterFrom = ChapterName;
            int cut = NextChapterScene.IndexOf('_');
            if (cut > 0 && PlayedChapters.Contains(NextChapterScene.Substring(0, cut)))
            {
                LogEvent("after this chapter: " + NextChapterScene + " was already played, so the end");
                NextChapterScene = "";
                return;
            }
            LogEvent("after this chapter: " + (NextChapterScene.Length > 0 ? NextChapterScene : "the end (no chapter yet)"));
        }

        /// <summary>The section after this one in script order (p00, s01 ... s05, e00), or null.</summary>
        private string NextSection(string current)
        {
            var sections = Sections();
            int k = sections.IndexOf(current);
            return k >= 0 && k + 1 < sections.Count ? sections[k + 1] : null;
        }

        private IEnumerator PlayVoice(StoryItem item, List<StoryItem> inlineSounds)
        {
            var parts = VoiceParts(item.Id, out var usedTake);
            if (parts == null)
            {
                Status = "Manca la registrazione: il testo resta a schermo";
                LogEvent("missing voice " + item.Id);
                CurrentClip = "(nessun audio)";
                yield return Wait(Mathf.Max(1.5f, item.Text.Length / missingVoiceCharsPerSecond));
                foreach (var s in inlineSounds) { if (Interrupted) yield break; yield return PlaySound(s); }
                yield break;
            }

            var staging = StagingFor(item);
            // A negative "pausa_dopo" lets the next item start before the end of the line (overlap).
            float overlap = Mathf.Min(0f, staging.PauseAfter ?? 0f);
            SpatialSource bed = StartLineBed(staging.Bed);
            try
            {
                int soundIndex = 0;
                for (int p = 0; p < parts.Count; p++)
                {
                    Status = parts.Count > 1 ? $"Voce, pezzo {p + 1} di {parts.Count}" : "Voce";
                    CurrentClip = parts[p].name + (usedTake != take ? $" (versione {usedTake})" : "");
                    var source = Spawn(parts[p], staging, item.Character, MarkerFor(item), isVoice: true);
                    bool lastPiece = p == parts.Count - 1 && soundIndex >= inlineSounds.Count;
                    yield return WaitForPlayback(source, lastPiece ? overlap : 0f);
                    if (Interrupted) yield break;
                    // A line split in N+1 parts has N sounds inside it, one after each part but the last.
                    if (p < parts.Count - 1 && soundIndex < inlineSounds.Count)
                    {
                        yield return InlineSound(inlineSounds[soundIndex++]);
                        if (Interrupted) yield break;
                    }
                }
                // Sounds that were not placed between parts (the line was recorded in one piece) play after it.
                while (soundIndex < inlineSounds.Count)
                {
                    yield return InlineSound(inlineSounds[soundIndex++]);
                    if (Interrupted) yield break;
                }
            }
            finally
            {
                if (bed != null) bed.FadeOut(bedFadeSeconds);
            }
        }

        private IEnumerator InlineSound(StoryItem sound)
        {
            yield return Wait(pauseAroundInlineSound);
            if (Interrupted) yield break;
            yield return PlaySound(sound);
            if (Interrupted) yield break;
            yield return Wait(pauseAroundInlineSound);
        }

        // A sound looping under one voice line (staging column "sottofondo").
        private SpatialSource StartLineBed(string soundId)
        {
            if (string.IsNullOrEmpty(soundId)) return null;
            if (!m_Sounds.TryGetValue(soundId, out var clip) && !m_ClipsByName.TryGetValue(soundId, out clip))
            {
                Debug.Log($"[Story] Missing background sound {soundId}");
                return null;
            }
            var bedItem = new StoryItem { Id = soundId, Kind = StoryItemKind.Sound };
            var go = new GameObject(clip.name + " (sottofondo)", typeof(AudioSource), typeof(SpatialSource));
            go.transform.SetParent(transform, true);
            var src = go.GetComponent<SpatialSource>();
            src.Init(this, listener, clip, StagingFor(bedItem), soundId + " (sottofondo)", soundMarker, loop: true, startGain: duckGain);
            src.TargetGain = duckGain;
            return src;
        }

        // Fades out the looping beds that end at this item (null = all of them).
        private void EndBedsUntil(string itemId)
        {
            for (int i = m_Beds.Count - 1; i >= 0; i--)
            {
                var (bed, until) = m_Beds[i];
                if (bed == null) { m_Beds.RemoveAt(i); continue; }
                if (itemId == null || until == itemId)
                {
                    bed.FadeOut(bedFadeSeconds);
                    m_Beds.RemoveAt(i);
                }
            }
        }

        private IEnumerator PlaySound(StoryItem item, double? scheduledStart = null)
        {
            if (!SoundClip(item.Id, out var clip))
            {
                Status = "Manca il suono " + item.Id;
                LogEvent("missing sound " + item.Id);
                CurrentClip = "(nessun audio)";
                Debug.Log($"[Story] Missing sound {item.Id}: {item.Text}");
                yield return Wait(0.6f);
                yield break;
            }
            var staging = StagingFor(item);
            Status = staging.Loop ? "Suono (continua di sottofondo)" : "Suono";
            CurrentClip = clip.name;
            // A sound that starts the battle loop is scheduled, so the loop can start exactly when it ends.
            // During a battle it replaces the loop on the next exchange boundary (chapter 2: the bass walks
            // home to F), and the new loop starts after "attesa" seconds (default: the whole sound).
            bool switchLoop = m_Battle != null && !string.IsNullOrEmpty(staging.BattleBase);
            if (switchLoop) scheduledStart = NextExchange(0.15);
            if (scheduledStart == null && !string.IsNullOrEmpty(staging.BattleBase))
                scheduledStart = Now + 0.1;
            var src = Spawn(clip, staging, item.Id, MarkerFor(item), loop: staging.Loop, scheduledStart: scheduledStart);
            if (staging.Loop) m_Beds.Add((src, staging.Until));
            double lead = scheduledStart.HasValue ? scheduledStart.Value - Now : 0;
            if (switchLoop)
            {
                int layers = m_Battle.Layers;
                string from = m_Battle.Prefix;
                StopBattle(scheduledStart.Value);
                StartBattle(staging, scheduledStart.Value + (staging.Wait ?? (double)clip.samples / clip.frequency));
                if (m_Battle != null) m_Battle.Layers = layers;
                LogEvent($"battle loop changes from {from} to {staging.BattleBase} after {item.Id}");
            }
            else if (!string.IsNullOrEmpty(staging.BattleBase))
                StartBattle(staging, scheduledStart.Value + (double)clip.samples / clip.frequency);
            yield return Wait((float)lead + (staging.Wait ?? clip.length));
        }

        private IEnumerator WaitForChoice(StoryItem item, List<StoryItem> list, int index)
        {
            WaitingChoice = true;
            m_Choice = -1;
            Status = "Aspetto una risposta: 1-4 o i pulsanti del Sasso (Spazio = il primo)";
            CurrentClip = "";
            while (m_Choice < 0 && !Interrupted) yield return null;
            WaitingChoice = false;
            if (m_Choice < 0) yield break;

            // The staging can say which button leads where ("scelte": 1=B;2=A). Otherwise button 1
            // picks branch A, button 2 branch B, ... if the following lines have that branch.
            var choices = StagingFor(item).Choices;
            if (choices.Count > 0)
            {
                if (choices.TryGetValue(m_Choice + 1, out var mapped))
                {
                    BranchChoice = mapped;
                    RememberNextChapter(item, mapped);
                    LogEvent("branch " + mapped);
                }
                else { m_Repeat = true; yield break; }  // a button with no meaning here: ask again
                yield break;
            }
            string letter = ((char)('A' + m_Choice)).ToString();
            for (int i = index + 1; i < list.Count && list[i].Kind != StoryItemKind.Convergence; i++)
            {
                if (list[i].Branch == letter)
                {
                    BranchChoice = letter;
                    RememberNextChapter(item, letter);
                    LogEvent("branch " + letter);
                    break;
                }
            }
        }

        private bool Interrupted => m_Skip || m_Repeat;

        // "...Hai sentito?" / "...vero?»" -> true (stage directions like [PAUSA] are ignored).
        private static bool EndsWithQuestion(string text)
        {
            var t = Regex.Replace(text ?? "", @"\[[^\]]*\]", "").TrimEnd(' ', '.', '»', '"', '!', '…');
            return t.EndsWith("?");
        }

        private IEnumerator Wait(float seconds)
        {
            // Editor pauses freeze audio, but the first resumed frame includes the wall-time gap.
            // Keep story delays on the audio clock instead of adding frame durations.
            double end = Now + seconds;
            while (Now < end)
            {
                if (Interrupted) yield break;
                yield return null;
            }
        }

        private IEnumerator WaitForPlayback(SpatialSource source, float overlap = 0f)
        {
            while (source != null)
            {
                if (Interrupted) yield break;
                if (!AudioListener.pause)
                {
                    var audio = source.Source;
                    if (!audio.isPlaying) yield break;
                    if (overlap < 0f && audio.timeSamples >=
                        Mathf.Max(0.1f, audio.clip.length + overlap) * audio.clip.frequency) yield break;
                }
                yield return null;
            }
        }

        private SpatialSource Spawn(AudioClip clip, StagingEntry staging, string label, Material marker,
            bool isVoice = false, bool loop = false, double? scheduledStart = null)
        {
            var go = new GameObject(clip.name, typeof(AudioSource), typeof(SpatialSource));
            go.transform.SetParent(transform, true);
            var src = go.GetComponent<SpatialSource>();
            src.Init(this, listener, clip, staging, label, marker, isVoice, loop, scheduledStart: scheduledStart);
            // Sounds that let the next line start early, and looping beds, keep playing underneath;
            // the rest stop on skip.
            bool overlaps = loop || (staging.Wait.HasValue && staging.Wait.Value < clip.length);
            if (!overlaps) m_Foreground.Add(src);
            else if (!loop && !isVoice) m_Tails.Add(src);
            return src;
        }

        private void StopForeground()
        {
            if (m_Skip || m_Repeat)
            {
                foreach (var s in m_Foreground)
                    if (s != null) s.Stop();
            }
            m_Foreground.Clear();
        }
    }
